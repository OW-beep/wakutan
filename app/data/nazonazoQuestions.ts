/**
 * ある item から、count 個ぶんの (2つのヒントを組み合わせた) なぞなぞを生成する。
 * ヒントの選び方・順番を変えることで、同じ答えでも違う問題文になる。
 */
export function generateRiddleQuestions(seed: number, hintsPerRiddle: 2 | 3, perItem: number): SimpleQuestion[] {
  const rand = seededRandom(seed);
  const qs: SimpleQuestion[] = [];

  for (const item of RIDDLE_ITEMS) {
    if (item.facts.length < hintsPerRiddle) continue;
    const seen = new Set<string>();
    let attempts = 0;
    let made = 0;
    while (made < perItem && attempts < perItem * 10) {
      attempts++;
      const shuffled = [...item.facts];
      for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(rand() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
      }
      const chosen = shuffled.slice(0, hintsPerRiddle);
      const key = chosen.join("|");
      if (seen.has(key)) continue;
      seen.add(key);
      made++;

      qs.push({
        question: `${chosen.join("。")}。なあに？`,
        answer: item.name,
        explanation: `${chosen[0]}のは「${item.name}」だよ。`,
      });
    }
  }

  return qs;
}
