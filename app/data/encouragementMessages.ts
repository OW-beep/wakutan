/** 日付をもとに、その日1日は同じメッセージを返す（サーバー・クライアントで一致させるためlocalStorage等は使わない） */
export function getTodayEncouragement(): string {
  const now = new Date();
  const dayOfYear = Math.floor(
    (Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) -
      Date.UTC(now.getFullYear(), 0, 0)) /
      (1000 * 60 * 60 * 24)
  );
  return encouragementMessages[dayOfYear % encouragementMessages.length];
}
