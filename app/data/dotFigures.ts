/**
 * 「おなじかたち」問題（点をせんで むすんだ ずけいを 見て、おなじものを かく）用の
 * データ型とヘルパー。
 *
 * gridSize が N のとき、たて・よこ (N+1) 個ずつの てん（かく座標 0..N）を並べ、
 * lines で「どのてんと どのてんを せんで むすぶか」を指定する。
 * 例: gridSize=2, lines=[[[0,0],[2,0]],[[2,0],[2,2]],[[2,2],[0,0]]] は
 *     3x3のてんの中で、さんかくけいを かく。
 */
export type Point = [number, number]; // [row, col]
export type DotFigure = {
  gridSize: number;
  lines: [Point, Point][];
};

