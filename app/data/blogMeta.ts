/**
 * 指定した記事と同じカテゴリの記事を最大 count 件返す。
 * 同カテゴリの記事が足りない場合は他カテゴリから補う。
 */
export function getRelatedArticles(
  currentSlug: string,
  count: number = 3
): BlogMetaEntry[] {
  const current = blogMeta.find((a) => a.slug === currentSlug);
  const others = blogMeta.filter((a) => a.slug !== currentSlug);

  const sameCategory = current
    ? others.filter((a) => a.category === current.category)
    : [];
  const rest = others.filter((a) => !sameCategory.includes(a));

  return [...sameCategory, ...rest].slice(0, count);
}
